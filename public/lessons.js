  function coursePosition(id, rootFen, history, cursor) {
    const course = OPENING_COURSES.find(c => c.id === id);
    if (!course) return null;
    let matched = 0;
    if (positionKey(rootFen) === positionKey(course.fen)) {
      while (matched < Math.min(cursor, course.moves.length) && (history[matched]?.uci || history[matched]) === course.moves[matched]) matched++;
    }
    const deviated = positionKey(rootFen) !== positionKey(course.fen) || matched < Math.min(cursor, course.moves.length);
    const status = deviated ? 'deviated' : cursor >= course.moves.length ? 'complete' : 'following';
    return { course, matched, status, next: status === 'following' ? course.steps[cursor] : null, previous: !deviated && cursor > 0 && cursor <= course.steps.length ? course.steps[cursor-1] : null, checkpoint: status === 'following' ? course.checkpoints[cursor] : null };
  }
